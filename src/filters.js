// Stillroom preset library.
//
// The look codes (A6, M5, C1 …) mirror the naming people recognise from VSCO so
// a familiar starting point is easy to find. Every look here is Stillroom's own
// numeric recipe mapped onto its own canvas pipeline — no third-party preset
// data is copied. Looks are organized into collections of clearly distinct
// styles (film, cinema, golden hour, moody, airy, vivid, retro, mono); the
// collection only shapes browsing, nothing is locked.

// Every preset carries the full recipe so switching looks never leaves a stale
// slider behind. Anything omitted falls back to neutral. `hsl` sits outside the
// recipe: it is preset-authored grading (per color channel), scaled by the
// intensity slider rather than hand-tuned.
const recipe = (overrides) => ({
  exposure: 0,
  contrast: 0,
  saturation: 0,
  temp: 0,
  tint: 0,
  highlights: 0,
  shadows: 0,
  whites: 0,
  blacks: 0,
  vibrance: 0,
  clarity: 0,
  sharpen: 0,
  fade: 0,
  grain: 0,
  grainSize: 0,
  vignette: 0,
  splitShadowHue: 0,
  splitShadowStrength: 0,
  splitHighlightHue: 0,
  splitHighlightStrength: 0,
  ...overrides,
})

