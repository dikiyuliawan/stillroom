// Internal channel map for per-recipe HSL grading carried by saved looks.
const HSL_CHANNELS = ['red', 'orange', 'yellow', 'green', 'blue', 'purple']

export const createHsl = () =>
  Object.fromEntries(HSL_CHANNELS.map((channel) => [channel, { h: 0, s: 0, l: 0 }]))

export const isHslNeutral = (hsl) =>
  !hsl ||
  HSL_CHANNELS.every((channel) => {
    const value = hsl[channel]
    return !value || (!value.h && !value.s && !value.l)
  })

// Preset-authored HSL grades follow the intensity slider: at 0% the look is
// fully neutral, at 100% fully graded. Rounding to integers keeps the values
// comparable with hand-set slider states.
export const scaleHsl = (hsl, amount) => {
  if (!hsl) return null
  const scaled = Object.fromEntries(
    HSL_CHANNELS.map((channel) => {
      const value = hsl[channel] || { h: 0, s: 0, l: 0 }
      return [
        channel,
        {
          h: Math.round((value.h || 0) * amount),
          s: Math.round((value.s || 0) * amount),
          l: Math.round((value.l || 0) * amount),
        },
      ]
    }),
  )
  return isHslNeutral(scaled) ? null : scaled
}
